import com.fasterxml.jackson.databind.JsonNode;

/**
 * A tool advertised to the M8B Governor: the contract the Governor may invoke through the tunnel.
 * Mirrors the Spring AI tool definition (name, description, JSON input schema) so that adding a new
 * {@code IMCPToolService} needs no protocol change.
 *
 * @param name        tool name, unique within the agent
 * @param description human/LLM-readable description
 * @param inputSchema JSON schema of the arguments object
 */
public record ToolDescriptor(String name, String description, JsonNode inputSchema) {}
