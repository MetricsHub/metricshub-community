import java.util.List;

/**
 * Runs a short-lived command and returns its standard output, used to discover the MetricsHub
 * service name of the running edition. Abstracted so the resolution logic is unit-testable without
 * spawning real processes.
 */
@FunctionalInterface
public interface CommandOutputReader {
	/**
	 * Runs the command and returns its output lines; an empty list when the command fails.
	 *
	 * @param command the command and its arguments
	 * @return the output lines, never {@code null}
	 */
	List<String> readLines(List<String> command);
}
