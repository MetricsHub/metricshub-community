import org.metricshub.engine.common.exception.ClientException;

/**
 * The failure of a request whose response cannot be replayed. The recorder records only the requests that answered,
 * so a missing recording stands for the error the host gave, which detection accepts (an invalid namespace, for
 * example), while a source fails on it.
 */
public class NoRecordedResponseException extends ClientException {

	private static final long serialVersionUID = 1L;

	/**
	 * Creates the exception with its message.
	 *
	 * @param message why the response cannot be replayed
	 */
	public NoRecordedResponseException(final String message) {
		super(message);
	}
}
