import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Represents a single IPMI emulation entry pairing a request type
 * with the filename of the recorded response.
 */
@Data
@AllArgsConstructor
@NoArgsConstructor
public class IpmiEmulationEntry {

	/**
	 * Recorded IPMI request identifier used as request key.
	 */
	private String request;

	/**
	 * The request bytes of a raw command; {@code null} for the other request types.
	 */
	private String query;

	/**
	 * File name containing the recorded command output.
	 */
	private String response;
}
