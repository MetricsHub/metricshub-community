/**
 * The load-time check of the strict content types (#1560, step 1): reads the desugared connector and reports every
 * rule that step 3 turns into a load error. It changes nothing, so the connector behaves as before.
 * <p>
 * The types are static: what each source's chain produces as written, the conversions generated by
 * {@link ContentTypeDesugaring} left out (see {@link ContentTypeDesugaring#writtenEndType}). The rules:
 * <ul>
 * <li>{@link Rule#TEXT_FEEDS_TABLE}: a text read by a <code>tableJoin</code>, a <code>tableUnion</code> member, a
 * mapping, a tool with columns, a compute that works on columns, an <code>internalDbQuery</code> table, an
 * <code>executeForEachEntryOf</code> or an awk variable;</li>
 * <li>{@link Rule#TABLE_FEEDS_TEXT}: a table read by a text compute or a <code>textUnion</code> member;</li>
 * <li>{@link Rule#TABLE_UNION_OF_TEXTS} (once per union) and {@link Rule#MIXED_UNION} (once per union, plus each text
 * member);</li>
 * <li>{@link Rule#STRING_LITERAL_ROWS}: a <code>;</code> string literal in <code>tables</code>,
 * <code>leftTable</code> or <code>rightTable</code>;</li>
 * <li>{@link Rule#TABLE_INTERPOLATED}: a table referenced in a field the engine interpolates: the fields a source or
 * a compute updates ({@link Source#update}, {@link Compute#update}, <code>authenticationToken</code> included) unless
 * the source reads its references as sources, and the mapping fields but its <code>source</code>;</li>
 * <li>{@link Rule#UNRESOLVED_REFERENCE}: a reference, anywhere in a source, a mapping or a tool result, to a source
 * the connector does not have;</li>
 * <li>{@link Rule#DEPRECATED_SYNTAX}: the <code>json2Csv</code> type, the ignored awk <code>input</code> and awk source
 * <code>inputFormat</code>.</li>
 * </ul>
 */
@Slf4j
public class ContentTypeCheck {

	/**
	 * Mapper giving the fields of the sources, the computes and the mappings.
	 */
	private static final ObjectMapper MAPPER = JsonHelper.buildObjectMapper();

	/**
	 * The message of a finding. It names where and which rule, never a value of the connector.
	 */
	private static final String MESSAGE = "Connector {} - Content type check: {} in {} at {}: expected {}, actual {} ({})";

	private static final String TABLE = ContentType.TABLE.name();
	private static final String TEXT = ContentType.TEXT.name();
	private static final String EXISTING_SOURCE = "an existing source";
	private static final String NONE = "none";

	private final String connectorId;
	private final Map<String, Source> sources = new LinkedHashMap<>();
	private final Map<Source, ContentType> types = new IdentityHashMap<>();
	private final List<ContentTypeFinding> findings = new ArrayList<>();

	private ContentTypeCheck(final String connectorId) {
		this.connectorId = connectorId;
	}

	/**
	 * Checks the desugared connector.
	 *
	 * @param connector   The connector, after the update chain
	 * @param connectorId The identifier of the connector in the findings
	 * @return the findings, in source order; none when the check itself fails, which never fails the load
	 */
	public static List<ContentTypeFinding> check(final Connector connector, final String connectorId) {
		final ContentTypeCheck check = new ContentTypeCheck(connectorId);
		try {
			check.run(connector);
		} catch (RuntimeException e) {
			// Report only: a connector the check cannot read loads as before
			log.warn(
				"Connector {} - Content type check failed, no finding reported: {}",
				connectorId,
				e.getClass().getName()
			);
			log.debug("Connector {} - Content type check failure:", connectorId, e);
			return new ArrayList<>();
		}
		return check.findings;
	}

	/**
	 * Logs each finding once: at INFO for a deprecated syntax, at WARN otherwise.
	 *
	 * @param findings The findings of a connector
	 */
	public static void log(final List<ContentTypeFinding> findings) {
		for (final ContentTypeFinding finding : findings) {
			final Object[] arguments = {
				finding.connectorId(),
				finding.rule(),
				finding.sourceKey(),
				finding.location(),
				finding.expected(),
				finding.actual(),
				finding.rule().hint() };
			if (finding.rule() == Rule.DEPRECATED_SYNTAX) {
				log.info(MESSAGE, arguments);
			} else {
				log.warn(MESSAGE, arguments);
			}
		}
	}

	private void run(final Connector connector) {
		ContentTypeDesugaring.forEachSource(connector, source -> sources.put(source.getKey(), source));
		sources.values().forEach(this::checkSource);
		if (connector.getMonitors() != null) {
			connector.getMonitors().forEach((name, job) -> {
				if (job instanceof StandardMonitorJob standard) {
					checkMapping("monitors." + name + ".discovery", standard.getDiscovery());
					checkMapping("monitors." + name + ".collect", standard.getCollect());
				} else if (job instanceof SimpleMonitorJob simple) {
					checkMapping("monitors." + name + ".simple", simple.getSimple());
				}
			});
		}
		if (connector.getTools() != null) {
			connector.getTools().forEach(this::checkTool);
		}
	}

	private void checkSource(final Source source) {
		final String key = source.getKey();

		// Every reference, wherever it is, designates a source of the connector
		final JsonNode tree = toTree(source, "key", "references");
		walk(
			tree,
			"",
			(field, value) -> references(value).stream()
				.filter(reference -> resolve(reference) == null)
				.forEach(reference -> add(key, field + " -> " + reference, Rule.UNRESOLVED_REFERENCE, EXISTING_SOURCE, NONE))
		);

		if (source instanceof TableUnionSource union) {
			checkTableUnion(key, union.getTables());
		} else if (source instanceof TextUnionSource textUnion && textUnion.getTexts() != null) {
			for (int index = 0; index < textUnion.getTexts().size(); index++) {
				for (final String reference : references(textUnion.getTexts().get(index))) {
					if (typeOf(reference) == ContentType.TABLE) {
						add(key, "texts[" + index + "] -> " + reference, Rule.TABLE_FEEDS_TEXT, TEXT, TABLE);
					}
				}
			}
		} else if (source instanceof TableJoinSource join) {
			checkJoinInput(key, "leftTable", join.getLeftTable());
			checkJoinInput(key, "rightTable", join.getRightTable());
		} else if (source instanceof InternalDbQuerySource query && query.getTables() != null) {
			for (int index = 0; index < query.getTables().size(); index++) {
				checkTableRead(key, "tables[" + index + "]", query.getTables().get(index).getSource());
			}
		} else if (source instanceof JawkSource jawk) {
			checkVariables(key, "", jawk.getVariables());
			if (jawk.isInputFormatDeclared()) {
				add(key, "inputFormat", Rule.DEPRECATED_SYNTAX, "no inputFormat", "inputFormat");
			}
		}

		if (source.isExecuteForEachEntryOf()) {
			checkTableRead(key, "executeForEachEntryOf", source.getExecuteForEachEntryOf());
		}

		// A source reading its references as sources (copy, static, unions, join, awk on a source) interpolates none
		if (!SourceUpdaterProcessor.isSourceWithProtectedReferences(source)) {
			final Source copy = source.copy();
			checkInterpolated(key, "", copy, copy::update);
		}

		checkComputes(source);
	}

	/**
	 * The chain as written: each compute's input against what flows into it.
	 */
	private void checkComputes(final Source source) {
		final String key = source.getKey();
		final List<Compute> computes = source.getComputes() == null
			? List.of()
			: source.getComputes().stream().filter(compute -> !ContentTypeDesugaring.isGenerated(compute)).toList();
		ContentType current = ContentTypeDesugaring.writtenStartType(source, sources);
		for (int index = 0; index < computes.size(); index++) {
			final Compute compute = computes.get(index);
			final String where = compute.getType() + " #" + index;
			// An awk reads whatever it gets: no input type
			final ContentType input = compute.getInputContentType();
			if (input != null && input != current) {
				add(
					key,
					where,
					input == ContentType.TABLE ? Rule.TEXT_FEEDS_TABLE : Rule.TABLE_FEEDS_TEXT,
					input.name(),
					current.name()
				);
			}
			if ("json2Csv".equalsIgnoreCase(compute.getType())) {
				add(key, where, Rule.DEPRECATED_SYNTAX, "json2Table", "json2Csv");
			}
			if (compute instanceof Awk awk) {
				checkVariables(key, where + " ", awk.getVariables());
				if (awk.isInputDeclared()) {
					add(key, where + " input", Rule.DEPRECATED_SYNTAX, "no input", "input");
				}
			}
			final Compute copy = compute.copy();
			checkInterpolated(key, where + " ", copy, copy::update);
			current = compute.getOutputContentType();
		}
	}

	/**
	 * A <code>tableUnion</code>: one finding for a union of texts, a mixed union and its text members, the string
	 * literals. An unresolved member counts as neither.
	 */
	private void checkTableUnion(final String key, final List<Object> tables) {
		if (tables == null) {
			return;
		}
		final Map<Integer, String> texts = new LinkedHashMap<>();
		boolean hasTable = false;
		for (int index = 0; index < tables.size(); index++) {
			final Object member = tables.get(index);
			if (member instanceof String reference && hasReference(reference)) {
				final ContentType type = typeOf(reference);
				if (type == ContentType.TEXT) {
					texts.put(index, reference.trim());
				} else if (type == ContentType.TABLE) {
					hasTable = true;
				}
			} else {
				if (member instanceof String) {
					add(key, "tables[" + index + "]", Rule.STRING_LITERAL_ROWS, "list of rows", "string");
				}
				hasTable = true;
			}
		}
		if (texts.isEmpty()) {
			return;
		}
		if (!hasTable) {
			add(key, "tables", Rule.TABLE_UNION_OF_TEXTS, TABLE, TEXT);
			return;
		}
		add(key, "tables", Rule.MIXED_UNION, TABLE, "TEXT and TABLE");
		texts.forEach(
			(index, reference) -> add(key, "tables[" + index + "] -> " + reference, Rule.TEXT_FEEDS_TABLE, TABLE, TEXT)
		);
	}

	private void checkJoinInput(final String key, final String field, final String table) {
		// Null: written as a list of rows
		if (table == null) {
			return;
		}
		if (hasReference(table)) {
			checkTableRead(key, field, table);
		} else {
			add(key, field, Rule.STRING_LITERAL_ROWS, "list of rows", "string");
		}
	}

	/**
	 * Awk variables: a source reference is exposed as that source's table.
	 */
	private void checkVariables(final String key, final String prefix, final Map<String, String> variables) {
		if (variables != null) {
			variables.forEach(
				(name, value) -> references(value).forEach(
					reference -> checkTableRead(key, prefix + "variables." + name, reference)
				)
			);
		}
	}

	/**
	 * A field read as a table: a text there is converted implicitly.
	 */
	private void checkTableRead(final String key, final String location, final String value) {
		for (final String reference : references(value)) {
			if (typeOf(reference) == ContentType.TEXT) {
				add(key, location + " -> " + reference, Rule.TEXT_FEEDS_TABLE, TABLE, TEXT);
			}
		}
	}

	/**
	 * The fields the engine interpolates are exactly those the holder's update visits: each table referenced there is
	 * serialized as <code>;</code> text (or, for <code>authenticationToken</code>, read as its first cell).
	 *
	 * @param holder A copy of the source or the compute, to name the fields
	 * @param update The holder's update
	 */
	private void checkInterpolated(
		final String key,
		final String prefix,
		final Object holder,
		final Consumer<UnaryOperator<String>> update
	) {
		// The holder's own fields: a source's computes are checked on their own. Fields holding the same value are
		// named in turn, so that each visit of that value reports a field of its own
		final Map<String, Deque<String>> fields = new HashMap<>();
		walk(
			toTree(holder, "key", "references", "computes"),
			"",
			(field, value) -> fields.computeIfAbsent(value, v -> new ArrayDeque<>()).add(field)
		);
		update.accept(value -> {
			final Deque<String> names = fields.get(value);
			final String field = names == null || names.isEmpty() ? "?" : names.poll();
			for (final String reference : references(value)) {
				if (typeOf(reference) == ContentType.TABLE) {
					add(key, prefix + field + " -> " + reference, Rule.TABLE_INTERPOLATED, TEXT, TABLE);
				}
			}
			return value;
		});
	}

	private void checkMapping(final String job, final AbstractMonitorTask task) {
		if (task == null || task.getMapping() == null) {
			return;
		}
		final String mappingSource = task.getMapping().getSource() == null ? NONE : task.getMapping().getSource().trim();
		final String location = job + ".mapping";
		walk(toTree(task.getMapping()), "", (field, value) -> {
			for (final String reference : references(value)) {
				final ContentType type = typeOf(reference);
				if (type == null) {
					add(
						mappingSource,
						location + "." + field + " -> " + reference,
						Rule.UNRESOLVED_REFERENCE,
						EXISTING_SOURCE,
						NONE
					);
				} else if ("source".equals(field)) {
					if (type == ContentType.TEXT) {
						add(mappingSource, location, Rule.TEXT_FEEDS_TABLE, TABLE, TEXT);
					}
				} else if (type == ContentType.TABLE) {
					add(mappingSource, location + "." + field + " -> " + reference, Rule.TABLE_INTERPOLATED, TEXT, TABLE);
				}
			}
		});
	}

	private void checkTool(final String name, final ConnectorTool tool) {
		if (tool.getResult() == null || !hasReference(tool.getResult().source())) {
			return;
		}
		final String location = "tools." + name + ".result";
		final Source result = ContentTypeDesugaring.toolResultSource(tool);
		if (result == null) {
			add(tool.getResult().source().trim(), location, Rule.UNRESOLVED_REFERENCE, EXISTING_SOURCE, NONE);
		} else
			if (
				tool.getResult().columns() != null &&
					!tool.getResult().columns().isEmpty() &&
					typeOf(result) == ContentType.TEXT
			) {
				add(result.getKey(), location, Rule.TEXT_FEEDS_TABLE, TABLE, TEXT);
			}
	}

	/**
	 * The static type of the referenced source, null when the connector has no such source.
	 */
	private ContentType typeOf(final String reference) {
		final Source source = resolve(reference);
		return source == null ? null : typeOf(source);
	}

	private ContentType typeOf(final Source source) {
		return types.computeIfAbsent(source, s -> ContentTypeDesugaring.writtenEndType(s, sources));
	}

	/**
	 * The referenced source, as the engine looks it up: the parser made every reference it could resolve absolute, and
	 * the engine looks up that exact key, with no fallback on a short reference that stayed short.
	 */
	private Source resolve(final String reference) {
		return sources.get(reference.trim());
	}

	private void add(
		final String sourceKey,
		final String location,
		final Rule rule,
		final String expected,
		final String actual
	) {
		findings.add(new ContentTypeFinding(connectorId, sourceKey, location, rule, expected, actual));
	}

	private static boolean hasReference(final String value) {
		return value != null && SOURCE_REF_PATTERN.matcher(value).find();
	}

	/**
	 * The <code>${source::...}</code> references of the value, trimmed, in order.
	 */
	private static List<String> references(final String value) {
		final List<String> references = new ArrayList<>();
		if (value != null) {
			final Matcher matcher = SOURCE_REF_PATTERN.matcher(value);
			while (matcher.find()) {
				references.add(matcher.group().trim());
			}
		}
		return references;
	}

	/**
	 * The JSON form of the value, without the excluded top-level fields; nothing when it cannot be serialized.
	 */
	private static JsonNode toTree(final Object value, final String... excluded) {
		try {
			final JsonNode tree = MAPPER.valueToTree(value);
			if (tree instanceof ObjectNode object) {
				object.remove(List.of(excluded));
			}
			return tree;
		} catch (IllegalArgumentException e) {
			return MissingNode.getInstance();
		}
	}

	/**
	 * Visits every text of the tree with its path, e.g. <code>computes[0].value</code>.
	 */
	private static void walk(final JsonNode node, final String path, final BiConsumer<String, String> visitor) {
		if (node.isTextual()) {
			visitor.accept(path, node.asText());
		} else if (node.isObject()) {
			node.fieldNames()
				.forEachRemaining(field -> walk(node.get(field), path.isEmpty() ? field : path + "." + field, visitor));
		} else if (node.isArray()) {
			for (int index = 0; index < node.size(); index++) {
				walk(node.get(index), path + "[" + index + "]", visitor);
			}
		}
	}
}
