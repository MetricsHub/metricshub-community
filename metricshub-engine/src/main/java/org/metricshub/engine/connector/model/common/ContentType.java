/**
 * The content type of a source result: free text (lines) or a table (rows of cells).
 * <p>
 * The content type is a static property of each source and compute class, never a YAML field: a source declares the
 * type it produces, a compute declares the type it consumes and the type it produces. The engine inserts the
 * conversions (<code>toText</code>, <code>toTable</code>) between a producer and a consumer of different types.
 */
public enum ContentType {
	/** Free text: lines separated by line feeds. */
	TEXT,
	/** A table: rows of cells. */
	TABLE
}
