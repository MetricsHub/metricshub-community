/**
 * The rows a {@link TableJoinSource} keeps: a row is the cells of the left row followed by the cells of the right row.
 * There is no right join: the table kept whole is always the left table.
 */
public enum JoinType {
	/**
	 * Only the left rows that match a right row.
	 */
	INNER,
	/**
	 * Every left row; the right side of an unmatched row is the default right line or empty cells.
	 */
	LEFT
}
