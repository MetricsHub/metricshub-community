import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;

/**
 * What a tool of a connector or of a protocol extension returns for one host: a table or a text.
 */
@JsonPropertyOrder("type")
public sealed interface ToolResult permits ToolTable, ToolText {
	/**
	 * @return {@code table} or {@code text}: the first field of the JSON, so that a reader does not guess the kind
	 *         of result from the other fields. A property rather than Jackson's type information, which is left
	 *         out of a value held as an {@code Object}, as the response of a host is.
	 */
	@JsonProperty("type")
	String type();
}
